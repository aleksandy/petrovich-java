package com.github.aleksandy.petrovich;

/**
 * Поддерживаемые падежи для склонения.
 *
 * <p>Порядок констант соответствует порядку окончаний в правилах:
 * родительный, дательный, винительный, творительный и предложный.
 * Индекс каждого падежа зависит от порядка объявления.
 */
public enum Case {

    /**
     * Именительный падеж (кто? что?).
     */
    NOMINATIVE,

    /**
     * Родительный падеж (кого? чего?).
     */
    GENITIVE,

    /**
     * Дательный падеж (кому? чему?).
     */
    DATIVE,

    /**
     * Винительный падеж (кого? что?).
     */
    ACCUSATIVE,

    /**
     * Творительный падеж (кем? чем?).
     */
    INSTRUMENTAL,

    /**
     * Предложный падеж (о ком? о чём?).
     */
    PREPOSITIONAL;

    /**
     * Возвращает индекс окончания в списке модификаторов правила.
     *
     * <p>Модификаторы хранятся в порядке родительного, дательного,
     * винительного, творительного и предложного падежей. Для
     * {@link #NOMINATIVE} возвращается {@code -1}, так как именительный падеж
     * не изменяет имя и модификатор не используется.
     *
     * @return индекс модификатора или {@code -1} для именительного падежа
     */
    public int getSuffixesIndex() {
        return ordinal() - 1;
    }

}
