package com.github.aleksandy.petrovich.rules;

/**
 * Набор правил склонения и определения пола.
 *
 * <p>Реализация решает, откуда брать правила (например, из YAML-ресурсов).
 * Правила склонения обязательны, правила определения пола могут быть пустыми.
 */
public interface Rules {

    /**
     * Возвращает правила склонения фамилий.
     *
     * @return правила склонения фамилий
     */
    RuleSet lastName();

    /**
     * Возвращает правила склонения имён.
     *
     * @return правила склонения имён
     */
    RuleSet firstName();

    /**
     * Возвращает правила склонения отчеств.
     *
     * @return правила склонения отчеств
     */
    RuleSet middleName();

    /**
     * Возвращает правила определения пола.
     *
     * @return правила определения пола
     */
    GenderRules gender();

}
